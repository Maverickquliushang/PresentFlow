"""Validate agent-authored slide specs and call the native PowerPoint renderer."""
import os
import shutil
import subprocess
from pathlib import Path

from .ingest import inspect_deck, inspect_pdf, markdown_script
from .storage import absolute, input_files, load_job, read_json, resolve_input, write_json


def native(script, arguments):
    if os.name != 'nt':
        raise ValueError('Native PPTX authoring/assembly currently needs Windows desktop PowerPoint. Use the agent presentation tool on this platform, then import the PPTX.')
    executable = shutil.which('pwsh') or shutil.which('powershell.exe')
    if not executable:
        raise ValueError('PowerShell is not available.')
    subprocess.run([executable, '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', str(script), *map(str, arguments)], check=True)


def validate_spec(spec, base, *, pages=None, template_slides=None):
    if not isinstance(spec.get('slides'), list) or not spec['slides']:
        raise ValueError('Talk spec requires a nonempty slides array.')
    result = dict(spec, slides=[])
    for index, slide in enumerate(spec['slides'], 1):
        if not isinstance(slide.get('title'), str) or not slide['title'].strip() or not isinstance(slide.get('notes'), str) or not slide['notes'].strip():
            raise ValueError(f'Slide {index} needs a title and spoken notes.')
        if any(line.strip().startswith(('Source:', 'Sources:', '来源：', 'Timing:')) for line in slide['notes'].splitlines()):
            raise ValueError(f'Slide {index}: move provenance/timing out of spoken notes.')
        item = dict(slide, slide=index)
        if pages is not None:
            for source in item.get('sources', []):
                page = source.get('page')
                if not isinstance(page, int) or isinstance(page, bool) or not 1 <= page <= pages:
                    raise ValueError(f'Slide {index}: source page outside PDF.')
        if template_slides is not None:
            number = item.get('template_slide')
            if not isinstance(number, int) or not 1 <= number <= template_slides:
                raise ValueError(f'Slide {index}: choose a valid template_slide.')
            if not isinstance(item.get('updates', {}), dict):
                raise ValueError('Template updates must map shape names to text.')
        for key in ('image',):
            if item.get(key):
                file = absolute(base / item[key])
                if not file.is_file():
                    raise ValueError(f'Slide {index}: missing image asset.')
                item[key] = str(file)
        table = item.get('table')
        if table:
            cols = table.get('columns', [])
            if not cols or any(len(row) != len(cols) for row in table.get('rows', [])):
                raise ValueError(f'Slide {index}: inconsistent table dimensions.')
        result['slides'].append(item)
    for key in ('conference_logo', 'institution_logo'):
        if result.get(key):
            file = absolute(base / result[key])
            if not file.is_file():
                raise ValueError(f'Missing branding asset: {key}')
            result[key] = str(file)
    return result


def compose(directory, spec_file, output):
    path, job = load_job(directory)
    files = input_files(path, job)
    spec_file, output = absolute(spec_file), absolute(output)
    if output.exists() or output in files.values():
        raise ValueError('Choose a new output filename; sources are preserved.')
    answers = job.get('answers', {})
    existing = files.get('deck')
    restyle = answers.get('deck_action') == 'restyle'
    template = files.get('template') if not existing or restyle else None
    paper = inspect_pdf(files['paper']) if files.get('paper') else None
    if paper and paper.get('encrypted'):
        raise ValueError('Read an unlocked source PDF before authoring from it.')
    spec = validate_spec(read_json(spec_file), spec_file.parent, pages=paper.get('page_count') if paper else None,
                         template_slides=inspect_deck(template)['slide_count'] if template else None)
    if template:
        inventory = inspect_deck(template)
        for item in spec['slides']:
            names = {s['name']: f'id:{s["id"]}' for s in inventory['slides'][item['template_slide'] - 1]['objects']}
            # PowerPoint may translate autogenerated shape names on open. IDs survive localization.
            item['updates'] = {names.get(key, key): value for key, value in item.get('updates', {}).items()}
            item['retain_text_shapes'] = [names.get(key, key) for key in item.get('retain_text_shapes', [])]
    if existing and not restyle and len(spec['slides']) != inspect_deck(existing)['slide_count']:
        raise ValueError('Preserving an existing deck requires one script entry per existing slide.')
    work = path.parent / 'private' / 'authoring'
    work.mkdir(parents=True, exist_ok=True)
    candidate = work / 'candidate.pptx'
    if candidate.exists():
        candidate.unlink()
    plan = dict(spec=spec, output=str(candidate), work=str(work),
                mode='notes' if existing and not restyle else 'template' if template else 'builtin',
                source=str(existing or template) if existing or template else None)
    write_json(work / 'plan.json', plan)
    native(Path(__file__).parent / 'native' / 'compose.ps1', ['-PlanPath', work / 'plan.json'])
    if not candidate.is_file():
        raise ValueError('PowerPoint did not create the requested file.')
    inspected = inspect_deck(candidate)
    if inspected['slide_count'] != len(spec['slides']):
        raise ValueError('Generated slide count differs from spec.')
    for actual, wanted in zip(inspected['slides'], spec['slides']):
        if ' '.join(actual['notes'].split()) != ' '.join(wanted['notes'].split()):
            raise ValueError('Generated notes differ from script.')
    if plan['mode'] == 'notes':
        from PIL import Image, ImageChops
        for i in range(1, inspected['slide_count'] + 1):
            name = f'slide_{i:02}.png'
            before = Image.open(work / 'before' / name).convert('RGB')
            after = Image.open(work / 'after' / name).convert('RGB')
            if before.size != after.size or ImageChops.difference(before, after).getbbox():
                raise ValueError(f'Visible layout changed on slide {i}.')
    output.parent.mkdir(parents=True, exist_ok=True)
    with candidate.open('rb') as src, output.open('xb') as dst:
        shutil.copyfileobj(src, dst)
    script_path = path.parent / 'speaker_script.md'
    script_path.write_text(markdown_script(spec['slides']), encoding='utf-8')
    job.setdefault('artifacts', {}).update(deck=str(output), script=str(script_path))
    write_json(path, job)
    write_json(work / 'receipt.json', dict(output=str(output), slides=inspected['slide_count'], mode=plan['mode'], notes_verified=True))
    return dict(output=str(output), script=str(script_path), mode=plan['mode'], slides=inspected['slide_count'])
